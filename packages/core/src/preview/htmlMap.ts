import fs from 'node:fs'
import path from 'node:path'
import type { FeatureCollection, GeoJsonProperties, Geometry } from 'geojson'
import { summarizeGeoJson } from '../convert/inspect.js'
import type { BBox } from '../types.js'

export interface PreviewHtmlOptions {
  title?: string
  crs?: string
  source?: string
  complianceNote?: string
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

/**
 * Generates a self-contained single-file HTML visual QA map using MapLibre GL JS
 * with zero API key requirements (OSM raster tiles + GeoJSON vector overlay).
 */
export function generatePreviewHtml(
  fc: FeatureCollection<Geometry, GeoJsonProperties>,
  options: PreviewHtmlOptions = {},
): string {
  const summary = summarizeGeoJson(fc)
  const title = escapeHtml(options.title ?? 'gisknife Visual QA Preview')
  const crs = escapeHtml(options.crs ?? 'EPSG:4326')
  const source = escapeHtml(options.source ?? 'local')
  const compliance = escapeHtml(
    options.complianceNote ??
      'Local preview generated by gisknife. Verify CRS and official map compliance before publishing.',
  )
  const bbox: BBox = summary.bbox ?? [-180, -85, 180, 85]
  const safeGeoJson = JSON.stringify(fc).replace(/<\//g, '<\\/')

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${title}</title>
  <link rel="stylesheet" href="https://unpkg.com/maplibre-gl@4.7.1/dist/maplibre-gl.css" />
  <script src="https://unpkg.com/maplibre-gl@4.7.1/dist/maplibre-gl.js"></script>
  <style>
    * { box-sizing: border-box; }
    body, html { margin: 0; padding: 0; height: 100%; font-family: ui-sans-serif, system-ui, -apple-system, sans-serif; background: #0f172a; color: #f8fafc; }
    #map { position: absolute; inset: 56px 0 28px 0; }
    .topbar { height: 56px; display: flex; align-items: center; justify-content: space-between; padding: 0 16px; background: #0f172a; border-bottom: 1px solid #1e293b; }
    .brand { font-weight: 700; font-size: 15px; display: flex; align-items: center; gap: 8px; }
    .badges { display: flex; gap: 8px; flex-wrap: wrap; }
    .badge { font-size: 12px; padding: 3px 8px; border-radius: 9999px; background: #1e293b; color: #cbd5e1; border: 1px solid #334155; }
    .badge.ok { border-color: #10b981; color: #6ee7b7; }
    .footer { position: absolute; left: 0; right: 0; bottom: 0; height: 28px; display: flex; align-items: center; justify-content: space-between; padding: 0 12px; font-size: 11px; color: #94a3b8; background: #0f172a; border-top: 1px solid #1e293b; }
    .controls { display: flex; gap: 6px; }
    button { background: #1e293b; color: #e2e8f0; border: 1px solid #334155; border-radius: 6px; padding: 5px 10px; font-size: 12px; cursor: pointer; }
    button:hover { background: #334155; }
    .maplibregl-popup-content { color: #0f172a; max-width: 320px; max-height: 260px; overflow: auto; font-size: 12px; }
    table { border-collapse: collapse; width: 100%; }
    td, th { text-align: left; padding: 2px 6px; border-bottom: 1px solid #e2e8f0; vertical-align: top; }
  </style>
</head>
<body>
  <header class="topbar">
    <div class="brand">
      <span>gisknife QA</span>
      <span style="color:#64748b;font-weight:400;">${title}</span>
    </div>
    <div class="badges">
      <span class="badge ok">${summary.featureCount} features</span>
      <span class="badge">${escapeHtml(summary.geometryTypes.join(', ') || 'Empty')}</span>
      <span class="badge">CRS: ${crs}</span>
      <span class="badge">Source: ${source}</span>
    </div>
    <div class="controls">
      <button id="fitBtn">Fit Bounds</button>
      <button id="toggleBtn">Toggle Layer</button>
    </div>
  </header>
  <div id="map"></div>
  <footer class="footer">
    <span>${compliance}</span>
    <span>BBox: [${bbox.map((n) => n.toFixed(4)).join(', ')}]</span>
  </footer>
  <script>
    const DATA = ${safeGeoJson};
    const BBOX = ${JSON.stringify(bbox)};
    const map = new maplibregl.Map({
      container: 'map',
      style: {
        version: 8,
        sources: {
          osm: {
            type: 'raster',
            tiles: ['https://tile.openstreetmap.org/{z}/{x}/{y}.png'],
            tileSize: 256,
            attribution: '© OpenStreetMap contributors'
          }
        },
        layers: [{ id: 'osm-base', type: 'raster', source: 'osm' }]
      },
      center: [(BBOX[0] + BBOX[2]) / 2, (BBOX[1] + BBOX[3]) / 2],
      zoom: 4
    });

    map.addControl(new maplibregl.NavigationControl(), 'top-right');

    map.on('load', () => {
      map.addSource('gisknife-layer', { type: 'geojson', data: DATA });
      map.addLayer({
        id: 'gk-fill',
        type: 'fill',
        source: 'gisknife-layer',
        filter: ['in', ['geometry-type'], ['literal', ['Polygon', 'MultiPolygon']]],
        paint: { 'fill-color': '#0ea5e9', 'fill-opacity': 0.28 }
      });
      map.addLayer({
        id: 'gk-line',
        type: 'line',
        source: 'gisknife-layer',
        paint: { 'line-color': '#0284c7', 'line-width': 2 }
      });
      map.addLayer({
        id: 'gk-point',
        type: 'circle',
        source: 'gisknife-layer',
        filter: ['in', ['geometry-type'], ['literal', ['Point', 'MultiPoint']]],
        paint: { 'circle-radius': 6, 'circle-color': '#f97316', 'circle-stroke-width': 1.5, 'circle-stroke-color': '#fff' }
      });

      if (DATA.features && DATA.features.length > 0 && BBOX[2] > BBOX[0]) {
        map.fitBounds([[BBOX[0], BBOX[1]], [BBOX[2], BBOX[3]]], { padding: 40, duration: 0 });
      }

      const inspectFeature = (e) => {
        const feat = e.features && e.features[0];
        if (!feat) return;
        const rows = Object.entries(feat.properties || {})
          .slice(0, 20)
          .map(([k, v]) => '<tr><th>' + k + '</th><td>' + String(v) + '</td></tr>')
          .join('');
        new maplibregl.Popup()
          .setLngLat(e.lngLat)
          .setHTML(rows ? '<table>' + rows + '</table>' : '<em>No properties</em>')
          .addTo(map);
      };

      ['gk-fill', 'gk-line', 'gk-point'].forEach((id) => {
        map.on('click', id, inspectFeature);
        map.on('mouseenter', id, () => { map.getCanvas().style.cursor = 'pointer'; });
        map.on('mouseleave', id, () => { map.getCanvas().style.cursor = ''; });
      });

      let visible = true;
      document.getElementById('toggleBtn').onclick = () => {
        visible = !visible;
        ['gk-fill', 'gk-line', 'gk-point'].forEach((id) => {
          map.setLayoutProperty(id, 'visibility', visible ? 'visible' : 'none');
        });
      };
      document.getElementById('fitBtn').onclick = () => {
        if (BBOX[2] > BBOX[0]) {
          map.fitBounds([[BBOX[0], BBOX[1]], [BBOX[2], BBOX[3]]], { padding: 40 });
        }
      };
    });
  </script>
</body>
</html>
`
}

export function writePreviewHtmlFile(
  outputPath: string,
  fc: FeatureCollection<Geometry, GeoJsonProperties>,
  options: PreviewHtmlOptions = {},
): string {
  const html = generatePreviewHtml(fc, options)
  const resolved = path.resolve(outputPath)
  fs.mkdirSync(path.dirname(resolved), { recursive: true })
  fs.writeFileSync(resolved, html, 'utf8')
  return resolved
}
